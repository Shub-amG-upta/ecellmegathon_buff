"""
Detailed analysis of one eval run (eval/run_eval.py output), for finding patterns.

  .venv/bin/python benchmarks/analyze.py <run.json> [--compare <other run.json>] [--log <live_monitor.log>]
                                         [--out ANALYSIS.md]

Sections: overview · accuracy per field with the kind of each error · extra values by kind · slices (turn
position, length, how many fields, what was asked, tags, source) · incident-type confusion · free-running
dialog failures · tool errors · latency (per call, per output token, first call) · temperature (monitor log)
· determinism against another run. Every number is computed from the files given; nothing is estimated.
Uses eval/nlu/cases.jsonl for each turn's tags, source and form before the turn.
"""
from __future__ import annotations

import argparse
import json
import re
import statistics as st
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))

from app.gate import content_words, support  # noqa: E402
from run_eval import text_match  # noqa: E402

FIELDS = ["t", "s", "l", "d", "p", "e", "a", "w"]
NAMES = {"t": "type", "s": "severity", "l": "location", "d": "time", "p": "persons", "e": "equipment",
         "a": "actions", "w": "witnesses"}


def pct(a, b):
    return f"{100 * a / b:.0f}%" if b else "–"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def q(s, n=70):
    s = str(s).replace("|", "/").replace("\n", " ")
    return (s[:n] + "…") if len(s) > n else s


# ---- error kinds -------------------------------------------------------------------
def kind_of_miss(k, gold, pred, raw_args):
    """Why a gold field was not matched."""
    if pred is None or pred == []:
        for k2, v2 in raw_args.items():                       # did the value land in another field?
            for item in (v2 if isinstance(v2, list) else [v2]):
                for g in (gold if isinstance(gold, list) else [gold]):
                    if k2 != k and isinstance(item, str) and text_match(item, g):
                        return f"put in {NAMES.get(k2, k2)}"
        return "left out"
    if k in ("t", "s"):
        return "wrong value"
    if isinstance(gold, list):
        pred = pred if isinstance(pred, list) else [pred]
        found = sum(any(text_match(p, g) for p in pred) for g in gold)
        return "some items missing" if found < len(gold) else "an item too many / reworded"
    g, p = set(content_words(gold)), set(content_words(pred))
    if p and p < g:
        return "cut short"
    if g and g < p:
        return "too long"
    return "different words"


def kind_of_extra(k, item, turn_case, case, gold_args):
    fb = turn_case["form_before"].get(k)
    before = fb if isinstance(fb, list) else ([fb] if fb else [])
    if any(str(item).lower() == str(b).lower() for b in before):
        return "repeats the form"
    for k2, v2 in {**gold_args, **case["gold_final"]}.items():
        if k2 != k:
            for g in (v2 if isinstance(v2, list) else [v2]):
                if isinstance(item, str) and isinstance(g, str) and text_match(item, g):
                    return f"belongs in {NAMES.get(k2, k2)}"
    if k in ("t", "s"):
        return "value not stated in this turn"
    sup = support(str(item), turn_case["user"])
    return "said, but not labelled" if sup >= 1.0 else "partly made up (passed the gate)"


# ---- main analysis -----------------------------------------------------------------
def analyze(run: dict, cases: dict, other: dict | None, log_text: str | None, name: str) -> str:
    tf, fr = run.get("turns") or [], run.get("dialogs") or []
    llm_turns = [t for t in tf if not t.get("fast_path")]
    L = [f"# Benchmark analysis: `{name}`", "",
         f"Label **{run.get('label')}** · split {run.get('split')} · model {run.get('model')} on {run.get('lane')} · "
         f"{run.get('laptop_time')} · fast path {'on' if any(t.get('fast_path') for t in tf) else 'off'}.",
         "Generated by `benchmarks/analyze.py`; every number below is counted from the run file.", ""]

    # overview
    golds = [(t, k, f) for t in tf for k, f in t["fields"].items()]
    ok = sum(f["ok"] for _, _, f in golds)
    L += ["## 1. Overview", "", table(["", "value"], [
        ["turns scored (teacher-forced)", len(tf)],
        ["… sent to the LLM / answered by code", f"{len(llm_turns)} / {len(tf) - len(llm_turns)}"],
        ["tool right", f"{sum(t['gold_tool'] == t['pred_tool'] for t in tf)}/{len(tf)} "
                       f"({pct(sum(t['gold_tool'] == t['pred_tool'] for t in tf), len(tf))})"],
        ["gold fields right", f"{ok}/{len(golds)} ({pct(ok, len(golds))})"],
        ["turns with every field right and no extra", sum(all(f['ok'] for f in t['fields'].values()) and not t['extra']
                                                          and t['gold_tool'] == t['pred_tool'] for t in tf)],
        ["values the gate dropped", sum(len(t["dropped"]) for t in tf)],
        ["dialogs (free-running) ended right / exactly right",
         f"{sum(d['state_ok'] for d in fr)}/{len(fr)} / "
         f"{sum(all(f['ok'] for f in d['fields'].values()) and not d['extra'] and d['state_ok'] for d in fr)}"]]), ""]

    # per field: right, and why wrong
    rows, examples = [], defaultdict(list)
    for k in FIELDS:
        fs = [(t, f) for t, kk, f in golds if kk == k]
        if not fs:
            continue
        kinds = Counter()
        for t, f in fs:
            if not f["ok"]:
                kd = kind_of_miss(k, f["gold"], f["pred"], (t.get("raw") or {}).get("args") or {})
                kinds[kd] += 1
                examples[k].append((t, f, kd))
        rows.append([NAMES[k], f"{sum(f['ok'] for _, f in fs)}/{len(fs)} ({pct(sum(f['ok'] for _, f in fs), len(fs))})",
                     ", ".join(f"{kd} {n}" for kd, n in kinds.most_common()) or "–"])
    L += ["## 2. Accuracy per field, and the kind of each error", "",
          "*left out*: no value given · *put in X*: the value went to another field · *cut short* / *too long*: "
          "same place or time, fewer or more words than the label · *some items missing*: a list field missed "
          "items · *wrong value*: a different type or severity.", "",
          table(["field", "right", "errors by kind"], rows), ""]
    for k in FIELDS:
        if examples[k]:
            L += [f"<details><summary>{NAMES[k]}: all {len(examples[k])} errors</summary>", "",
                  table(["turn", "kind", "label", "model", "user said"],
                        [[f"`{t['case']}#{t['turn']}`", kd, q(f['gold'], 40), q(f['pred'], 40), q(t['user'], 80)]
                         for t, f, kd in examples[k]]), "", "</details>", ""]

    # extras
    ek, ex_rows = Counter(), defaultdict(list)
    for t in tf:
        tc = cases[t["case"]]["turns"][t["turn"]]
        for k, v in t["extra"].items():
            for item in (v if isinstance(v, list) else [v]):
                kd = kind_of_extra(k, item, tc, cases[t["case"]], t["fields"] and {kk: f["gold"] for kk, f in t["fields"].items()})
                ek[(NAMES[k], kd)] += 1
                ex_rows[kd].append((t, k, item))
    by_kind = Counter()
    for (fld, kd), n in ek.items():
        by_kind[kd] += n
    L += ["## 3. Extra values (filled, but not in this turn's label)", "",
          "*repeats the form*: the same value again (harmless) · *belongs in X*: a labelled value put in the wrong "
          "field · *said, but not labelled*: every word is in what the user said: over-extraction, or a gap in the "
          "label · *partly made up*: some words not said (it passed the gate's 60% rule) · *value not stated*: "
          "a type/severity the turn didn't say.", "",
          table(["kind", "count", "by field"],
                [[kd, n, ", ".join(f"{f} {c}" for (f, k2), c in sorted(ek.items()) if k2 == kd)]
                 for kd, n in by_kind.most_common()]), ""]
    for kd, items in ex_rows.items():
        L += [f"<details><summary>{kd}: {len(items)} values</summary>", "",
              table(["turn", "field", "value", "user said"],
                    [[f"`{t['case']}#{t['turn']}`", NAMES[k], q(v, 45), q(t['user'], 80)] for t, k, v in items[:40]]),
              "", "</details>", ""]

    # slices
    def acc(sel):
        fs = [f for t in sel for f in t["fields"].values()]
        x = sum(bool(t["extra"]) for t in sel)
        return [len(sel), f"{sum(f['ok'] for f in fs)}/{len(fs)} ({pct(sum(f['ok'] for f in fs), len(fs))})" if fs else "–",
                f"{x} ({pct(x, len(sel))})"]

    def words(t):
        return len(t["user"].split())

    slices = [("first turn of the dialog", [t for t in tf if t["turn"] == 0]),
              ("later turns", [t for t in tf if t["turn"] > 0]),
              ("answers a question (asked ≠ none)", [t for t in tf if t["asked"]]),
              ("≤ 5 words", [t for t in tf if words(t) <= 5]),
              ("6–15 words", [t for t in tf if 6 <= words(t) <= 15]),
              ("16–30 words", [t for t in tf if 16 <= words(t) <= 30]),
              ("> 30 words", [t for t in tf if words(t) > 30]),
              ("0–1 labelled fields", [t for t in tf if len(t["fields"]) <= 1]),
              ("2–3 labelled fields", [t for t in tf if 2 <= len(t["fields"]) <= 3]),
              ("4–5 labelled fields", [t for t in tf if 4 <= len(t["fields"]) <= 5]),
              ("6+ labelled fields", [t for t in tf if len(t["fields"]) >= 6])]
    L += ["## 4. Where it goes wrong: slices", "",
          table(["turns", "n", "fields right", "turns with extra"], [[n] + acc(s) for n, s in slices if s]), ""]
    tags = defaultdict(list)
    for t in tf:
        c = cases[t["case"]]
        for tg in c["tags"]:
            tags[tg].append(t)
        tags["source: hand-written (H)" if c["source"] == "H" else "source: real incident"].append(t)
    rows = sorted(([tg] + acc(s) for tg, s in tags.items() if len(s) >= 4),
                  key=lambda r: float(re.search(r"\((\d+)%\)", r[2]).group(1)) if "%" in r[2] else 999)
    L += ["By tag (tags with ≥ 4 turns; worst first):", "", table(["tag", "n", "fields right", "turns with extra"], rows), ""]

    # type confusion
    conf = Counter((t["fields"]["t"]["gold"], t["fields"]["t"]["pred"]) for t in tf if "t" in t["fields"])
    wrong = [(g, p, n) for (g, p), n in conf.items() if g != p]
    if wrong:
        L += ["## 5. Incident type: what was confused with what", "",
              table(["label", "model said", "times"], sorted(([g, p, n] for g, p, n in wrong), key=lambda r: -r[2])),
              "", f"Right: {sum(n for (g, p), n in conf.items() if g == p)}/{sum(conf.values())}.", ""]

    # free-running
    if fr:
        why = Counter()
        rows = []
        for d in fr:
            if d["state_ok"] and all(f["ok"] for f in d["fields"].values()):
                continue
            wrong_f = [NAMES[k] for k, f in d["fields"].items() if not f["ok"]]
            reason = ("did not finish: still missing " + ", ".join(d["missing"]) if not d["state_ok"] and d["missing"]
                      else "ended in the wrong state" if not d["state_ok"] else "finished, with wrong fields")
            why[reason.split(":")[0]] += 1
            rows.append([f"`{d['case']}`", reason, ", ".join(wrong_f) or "–", d["final_state"]])
        L += ["## 6. Free-running: why dialogs failed", "", table(["reason", "dialogs"], why.most_common()), "",
              "<details><summary>every failed dialog</summary>", "",
              table(["dialog", "reason", "wrong fields", "final state"], rows), "", "</details>", ""]

    # tool errors
    te = [t for t in tf if t["gold_tool"] != t["pred_tool"]]
    if te:
        L += ["## 7. Wrong tool", "", table(["turn", "label", "model", "user said", "model args"],
              [[f"`{t['case']}#{t['turn']}`", t["gold_tool"], t["pred_tool"], q(t["user"], 60),
                q(json.dumps((t.get('raw') or {}).get('args', {})), 60)] for t in te]), ""]

    # latency
    lat = [t["llm"] for t in llm_turns if t["llm"].get("wall_ms") is not None]
    if lat:
        w = sorted(x["wall_ms"] for x in lat)
        pts = [(x["decode_tokens"], x["decode_ms"]) for x in lat if x.get("decode_tokens") and x.get("decode_ms")]
        n = len(pts)
        mx, my = sum(a for a, _ in pts) / n, sum(b for _, b in pts) / n
        slope = sum((a - mx) * (b - my) for a, b in pts) / max(1e-9, sum((a - mx) ** 2 for a, _ in pts))
        inter = my - slope * mx
        pre = [x["prefill_tokens"] for x in lat if x.get("prefill_tokens") is not None]
        first = [t["llm"] for t in llm_turns if t["turn"] == 0 and t["llm"].get("wall_ms")]
        later = [t["llm"] for t in llm_turns if t["turn"] > 0 and t["llm"].get("wall_ms")]
        L += ["## 8. Latency (LLM calls)", "", table(["", "value"], [
            ["calls", len(lat)],
            ["wall ms: median / p90 / max", f"{st.median(w):.0f} / {w[int(0.9 * (len(w) - 1))]:.0f} / {w[-1]:.0f}"],
            ["decode: ms per output token (fit) + fixed part", f"{slope:.1f} ms/token + {inter:.0f} ms "
                                                              f"(≈ {1000 / slope:.1f} tok/s)" if slope > 0 else "–"],
            ["output tokens: median / max", f"{st.median(a for a, _ in pts):.0f} / {max(a for a, _ in pts)}"],
            ["new prompt tokens per call: median / max", f"{st.median(pre):.0f} / {max(pre)}  (the rest is cached)"
             if pre else "–"],
            ["first turn of a dialog: median wall ms", f"{st.median(x['wall_ms'] for x in first):.0f}" if first else "–"],
            ["later turns: median wall ms", f"{st.median(x['wall_ms'] for x in later):.0f}" if later else "–"],
            ["share of call time spent writing output (decode)",
             pct(sum(x.get('decode_ms') or 0 for x in lat), sum(x['wall_ms'] for x in lat))]]), ""]

    # temperature from the monitor log
    if log_text:
        temp, rows = None, []
        for ln in log_text.splitlines():
            m = re.search(r"BOARD .*NPU ([\d.]+) °C", ln)
            if m:
                temp = float(m.group(1))
                continue
            m = re.search(r"decode (\d+) tok (\d+) ms \(([\d.]+) tok/s\)", ln)
            if m and temp is not None and int(m.group(1)) >= 8:
                rows.append((temp, float(m.group(3))))
        bands = [(0, 60), (60, 80), (80, 95), (95, 200)]
        L += ["## 9. Temperature and output speed (monitor log, calls with ≥ 8 output tokens)", "",
              table(["NPU °C (last reading before the call)", "calls", "median tok/s"],
                    [[f"{lo}–{hi if hi < 200 else '…'}", len(v), f"{st.median(v):.1f}"]
                     for lo, hi in bands if (v := [s for t, s in rows if lo <= t < hi])]),
              "", "Observed, not a controlled test: the call mix differs between bands, and the log covers every call in "
              "the file (it can span more than this run).", ""]

    # determinism
    if other:
        a = {(t["case"], t["turn"]): t for t in other.get("turns", [])}
        both = [(t, a[(t["case"], t["turn"])]) for t in llm_turns if (t["case"], t["turn"]) in a
                and not a[(t["case"], t["turn"])].get("fast_path")]
        same = [x for x in both if json.dumps(x[0]["raw"], sort_keys=True) == json.dumps(x[1]["raw"], sort_keys=True)]
        diff = [x for x in both if x not in same]
        L += ["## 10. Same turns in the other run", "",
              f"Turns sent to the LLM in both runs: {len(both)}; identical model output: {len(same)}; different: "
              f"{len(diff)}.", ""]
        if diff:
            L += [table(["turn", "this run", "other run"],
                        [[f"`{x[0]['case']}#{x[0]['turn']}`", q(json.dumps(x[0]['raw']), 60), q(json.dumps(x[1]['raw']), 60)]
                         for x in diff[:15]]), ""]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--compare")
    ap.add_argument("--log")
    ap.add_argument("--out")
    a = ap.parse_args()
    cases = {c["id"]: c for c in map(json.loads, (ROOT / "eval" / "nlu" / "cases.jsonl").read_text().splitlines())}
    run = json.loads(Path(a.run).read_text())
    other = json.loads(Path(a.compare).read_text()) if a.compare else None
    log = Path(a.log).read_text() if a.log else None
    md = analyze(run, cases, other, log, Path(a.run).name)
    if a.out:
        Path(a.out).write_text(md)
        print(f"wrote {a.out}")
    else:
        print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
